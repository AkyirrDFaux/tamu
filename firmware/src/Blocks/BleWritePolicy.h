#pragma once

// Who may write the `BLE Settings` block (Blocks/BleSettings.h).
//
// Owner ruling, 2026-11-05: "since we have a USB-less reset way, we can allow all operations over
// BLE now." The block was USB-only because a phone could lock the owner out of the radio it was
// reaching the device through - no way back except a cable. The GPIO8 reset (Blocks/BleResetHold.h,
// Devices/Tamu_v2.0A/BleResetPin.h) is that way back, so the rule becomes the LINK instead of the
// cable:
//
//   - a frame that arrived over USB is writable: the cable IS the owner's access to the device;
//   - a frame that arrived over BLE is writable only while the link it arrived on is a SESSION
//     this device admitted - encrypted, bonded and (with a passkey set) authenticated. That is
//     exactly `AppBLELinkSecured()` (Devices/Tamu_v2.0A/AppBLE.h), the flag set by the session
//     gate and cleared on disconnect;
//   - anything else - a bus frame, a locally generated write - is not writable, as before.
//
// Why it is not simply `true`: "not USB" is not proof of anything. A frame can arrive over the bus,
// or be generated by a script, and it can arrive on a BLE link that is still unencrypted for the
// few milliseconds between the connection and the security procedure. The GATT table alone cannot
// answer the question either: its `*_AUTHEN` bits are baked in at radio start, while the passkey
// can change at runtime (the connect gate re-checks the policy on every link for exactly that
// reason). The session flag is the one place that says "this link met the policy that is in force
// now", so the write gate asks it instead of trusting the transport.
//
// The READ path is unchanged: none of this touches a field's read-out.
//
// Host-clean so test/native/ble_write_test.cpp can drive every combination; the device glue asks it
// with the frame's own link (Core/Functions/AppInterface.h publishes it while a frame is dispatched)
// and the live session flag.

#include <cstdint>

// The three inputs, named rather than positional at the call site.
inline bool BleWriteAllowed(bool OverUsb, bool OverBle, bool BleLinkSecured)
{
    if (OverUsb)
        return true;
    // A BLE write is the owner's phone only when the link it came in on is a secured session -
    // never merely because it is not the cable.
    return OverBle && BleLinkSecured;
}
